"""Cut assets/handwriting.jpg into a glyph sprite + signature for notebook.html.

Usage: python tools/handwriting_sprite.py
Writes assets/notebook/glyphs.png, signature.png and handwriting.js. The PNGs are
white ink on transparent so the page uses them as CSS masks (ink colour comes from
CSS). handwriting.js carries the metrics plus both images as data URIs, because
browsers refuse mask images from file:// - this keeps notebook.html working when
opened straight from disk.
"""
import base64
import json
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "handwriting.jpg"
OUT = ROOT / "assets" / "notebook"

# Letters in the order they were written, per row. Each row is a list of
# (letter, number of connected strokes) - i and j have a separate dot.
ROW1 = [(c, 2 if c in "ij" else 1) for c in "AaBbCcDdEeFfGgHhIiJjKkLlMmNn"]
ROW2 = [(c, 1) for c in "OoPpQqRrSsTtUuVvWwXxYyZz"]
DESCENDERS = set("gjpqy")


def alpha_from(gray):
    # paper ~250, ink ~20 -> 0..1; the floor drops faint JPEG noise
    return np.clip((215.0 - gray) / 170.0, 0, 1)


def main():
    gray = np.array(Image.open(SRC).convert("L")).astype(float)
    ink = gray < 110
    ink[:330] = False  # notes-app toolbar
    ink[1500:] = False  # page-curl icon
    lab, _ = ndimage.label(ink)
    alpha = alpha_from(gray)

    name, rows = [], {1: [], 2: []}
    for i, s in enumerate(ndimage.find_objects(lab)):
        if (lab[s] == i + 1).sum() < 30:
            continue
        box = [s[1].start, s[1].stop, s[0].start, s[0].stop, i + 1]
        if box[3] < 760:
            name.append(box)
            continue
        cy = (box[2] + box[3]) / 2
        divider = 930 - (box[0] - 600) * 90 / 1400  # the rows slope upward
        rows[1 if cy < divider else 2].append(box)
    for r in rows.values():
        r.sort()

    def cut(boxes, pad=6):
        x0 = min(b[0] for b in boxes) - pad
        x1 = max(b[1] for b in boxes) + pad
        y0 = min(b[2] for b in boxes) - pad
        y1 = max(b[3] for b in boxes) + pad
        keep = np.isin(lab[y0:y1, x0:x1], [b[4] for b in boxes])
        keep = ndimage.binary_dilation(keep, iterations=4)
        a = (alpha[y0:y1, x0:x1] * keep * 255).astype(np.uint8)
        rgba = np.zeros(a.shape + (4,), np.uint8)
        rgba[..., :3] = 255
        rgba[..., 3] = a
        return Image.fromarray(rgba), (x0, y0, x1, y1)

    glyphs = {}
    for spec, boxes in ((ROW1, rows[1]), (ROW2, rows[2])):
        assert sum(n for _, n in spec) == len(boxes), (len(boxes), spec)
        k = 0
        for ch, n in spec:
            img, bb = cut(boxes[k:k + n])
            glyphs[ch] = {"img": img, "box": bb}
            k += n

    # Baseline: most letters sit on their own bottom edge. Descenders (and the
    # dipping J/Q) borrow the bottom of a neighbour written alongside them.
    def bottom(ch):
        return glyphs[ch]["box"][3] - 6

    base = {ch: bottom(ch) for ch in glyphs}
    for ch in DESCENDERS - {"j", "q"}:
        base[ch] = bottom(ch.upper())
    base["J"] = base["j"] = (bottom("I") + bottom("K")) / 2
    base["Q"] = base["q"] = (bottom("P") + bottom("R")) / 2

    cap = np.median([bottom(c) - glyphs[c]["box"][1] - 6 for c in "ABDEHKLMN"])

    OUT.mkdir(parents=True, exist_ok=True)
    order = list(glyphs)
    gap = 4
    width = sum(glyphs[c]["img"].width + gap for c in order)
    height = max(glyphs[c]["img"].height for c in order)
    sheet = Image.new("RGBA", (width, height), (255, 255, 255, 0))
    meta = {"cap": float(cap), "w": width, "h": height, "glyphs": {}}
    x = 0
    for c in order:
        g = glyphs[c]
        sheet.paste(g["img"], (x, 0))
        meta["glyphs"][c] = {
            "x": x,
            "w": g["img"].width,
            "h": g["img"].height,
            "base": float(base[c] - g["box"][1]),  # px from glyph top to baseline
        }
        x += g["img"].width + gap
    sheet.save(OUT / "glyphs.png", optimize=True)

    sig, _ = cut(name, pad=10)
    sig.save(OUT / "signature.png", optimize=True)

    def data_uri(path):
        return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode()

    meta["sprite"] = data_uri(OUT / "glyphs.png")
    meta["signature"] = {"src": data_uri(OUT / "signature.png"), "w": sig.width, "h": sig.height}
    (OUT / "handwriting.js").write_text(
        "// generated by tools/handwriting_sprite.py - do not edit\n"
        "window.HANDWRITING=" + json.dumps(meta, separators=(",", ":")) + ";\n"
    )
    print(f"{len(order)} glyphs, sheet {width}x{height}, cap {cap:.0f}px")


if __name__ == "__main__":
    main()
